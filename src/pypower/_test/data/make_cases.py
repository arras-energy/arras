"""Make the GLM case files of the pypower autotests

Converts each PYPOWER case file `caseNAME.py` in this folder to
`caseNAME.glm`, as gridlabd's `#input "caseNAME.py" -t pypower` does
(`converters/py2glm.py`, `convert_pypower()`), and writes the assert
objects that check its solution to `caseNAME_verify.glm`, as the
autotests' `verify.py` does.

The only change from `py2glm.py`: `apf` values are written without the
unit `pu`, because `apf` has no unit and `arras` refuses a unit on a
unitless property.

Run from this folder:

    python3 make_cases.py [NAME ...]

The `#define MRES`/`ARES` tolerances of the verify files are set by the
test GLM files that include them.
"""

import os
import sys
import importlib

DATASPEC = {
    "bus" : {
        "bus_i": "{:.0f}", "type": "{:.0f}", "Pd": "{:g} MW", "Qd": "{:g} MVAr", "Gs": "{:g} MW",
        "Bs": "{:g} MVAr", "area": "{:.0f}", "Vm": "{:g} pu.kV", "Va": "{:g} deg", "baseKV": "{:g} kV",
        "zone": "{:.0f}", "Vmax": "{:g} pu.kV", "Vmin": "{:g} pu.kV",
    },
    "gen": {
        "bus": "{:.0f}", "Pg": "{:g} MW", "Qg": "{:g} MVAr", "Qmax": "{:g} MVAr", "Qmin": "{:g} MVAr",
        "Vg": "{:g} pu.kV", "mBase": "{:g} MVA", "status": "{:.0f}", "Pmax": "{:g} MW", "Pmin": "{:g} MW",
        "Pc1": "{:g} MW", "Pc2": "{:g} MW", "Qc1min": "{:g} MVAr", "Qc1max": "{:g} MVAr",
        "Qc2min": "{:g} MVAr", "Qc2max": "{:g} MVAr", "ramp_agc": "{:g} MW/min", "ramp_10": "{:g} MW",
        "ramp_30": "{:g} MW", "ramp_q": "{:g} MVAr/min", "apf": "{:g}",
    },
    "branch": {
        "fbus": "{:.0f}", "tbus": "{:.0f}", "r": "{:g} pu.Ohm", "x": "{:g} pu.Ohm", "b": "{:g} pu.S",
        "rateA": "{:g} MVA", "rateB": "{:g} MVA", "rateC": "{:g} MVA", "ratio": "{:g} pu",
        "angle": "{:g} deg", "status": "{:.0f}", "angmin": "{:g} deg", "angmax": "{:g} deg",
    }
}
"""Columns and formats (`py2glm.py` `DATASPEC`, except `apf`)"""

MODIFY = {
    "gen" : {"parent": ("bus", lambda x: f"pp_bus_{int(x[0])}")},
    "branch": {"from": ("fbus", lambda x: f"pp_bus_{int(x[0])}"), "to": ("tbus", lambda x: f"pp_bus_{int(x[1])}")},
}
"""References added after a column (`py2glm.py` `MODIFY`)"""

def convert(name:str) -> None:
    """Write `NAME.glm` from `NAME.py` (`py2glm.py` `convert_pypower()`)"""
    data = getattr(importlib.import_module(name), name)()
    nl = "\n"
    with open(f"{name}.glm", "w", encoding="utf-8") as glm:
        glm.write(f"""// generated by make_cases.py from {name}.py (gridlabd converters/py2glm.py -t pypower)
module pypower
{{
    version {data['version']};
    baseMVA {data['baseMVA']};
}}
""")
        for table, spec in DATASPEC.items():
            glm.write(f"{nl}//{nl}// {table}{nl}//{nl}")
            for n, line in enumerate(data[table]):
                glm.write(f"""object pypower.{table}
{{{nl}    name "pp_{table}_{n+1}";
""")
                for m, item in enumerate(spec.items()):
                    glm.write(f"    {item[0]} {item[1].format(line[m])};{nl}")
                    for key, value in [(y, z) for y, z in MODIFY.get(table, {}).items() if item[0] == z[0]]:
                        glm.write(f"""    {key} "{value[1](line)}";{nl}""")
                glm.write("}\n")
        if "gencost" in data:
            glm.write("\n//\n// gencost\n//\n")
            for n, line in enumerate(data["gencost"]):
                glm.write(f"""object pypower.gencost
{{{nl}    name pp_gencost_{n+1};
    parent "pp_gen_{n+1}";
    model {int(line[0])};
    startup {line[1]};
    shutdown {line[2]};
    costs "{','.join([str(x) for x in line[4:]])}";
}}
""")
        if "dcline" in data:
            glm.write("\n//\n// dcline\n//\n")
            for n, line in enumerate(data["dcline"]):
                print("object pypower.dcline\n{", file=glm)
                print(f"    name pp_dcline_{n};", file=glm)
                print(f"    from pp_bus_{line[0]:.0f};", file=glm)
                print(f"    to pp_bus_{line[1]:.0f};", file=glm)
                print(f"    status {line[2]:.0f};", file=glm)
                print(f"    Sfrom {line[3]:.6g}{line[4]:+.6g}j MVA;", file=glm)
                print(f"    Sto {line[5]:.6g}{line[6]:+.6g}j MVA;", file=glm)
                print(f"    Vfrom {line[7]:.6g} pu.V;", file=glm)
                print(f"    Vto {line[8]:.6g} pu.V;", file=glm)
                print(f"    Pmin {line[9]:.6g} MW;", file=glm)
                print(f"    Pmax {line[10]:.6g} MW;", file=glm)
                print(f"    Qminf {line[11]:.6g} MVAr;", file=glm)
                print(f"    Qmaxf {line[12]:.6g} MVAr;", file=glm)
                print(f"    Qmint {line[13]:.6g} MVAr;", file=glm)
                print(f"    Qmaxt {line[14]:.6g} MVAr;", file=glm)
                print(f"    loss0 {line[15]:.6g} MW;", file=glm)
                print(f"    loss1 {line[16]:.6g} MW/MW;", file=glm)
                print("}", file=glm)

def verify(name:str) -> None:
    """Write `NAME_verify.glm` (the autotests' `verify.write_glm()`)"""
    data = getattr(importlib.import_module(name), name)()
    with open(f"{name}_verify.glm", "w", encoding="utf-8") as fh:
        for bus in data['bus']:
            print(f"""object assert
{{
    parent pp_bus_{bus[0]:.0f};
    target Vm;
    relation ==;
    value {bus[7]:.3f};
    within ${{MRES}};
}}
object assert
{{
    parent pp_bus_{bus[0]:.0f};
    target Va;
    relation ==;
    value {bus[8]:.2f};
    within ${{ARES}};
}}
""", file=fh)

CASES = ["case9", "case9dc", "case4gs", "case14", "case14e", "case30", "case39", "case57", "case118"]
"""Cases used by the autotests"""

VERIFIED = ["case14", "case39", "case57", "case118"]
"""Cases whose autotests check the solution with `verify.py`"""

if __name__ == "__main__":
    sys.path.insert(0, os.getcwd())
    for case in sys.argv[1:] or CASES:
        try:
            convert(case)
        except Exception as err: # pylint: disable=broad-exception-caught
            print(f"{case}: {type(err).__name__}: {err}", file=sys.stderr)
            continue
        if case in VERIFIED:
            verify(case)
